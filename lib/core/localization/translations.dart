/// Central translation tables for GlowCare AI.
///
/// Keys are the English source strings (or short semantic keys). Anything
/// missing from a table falls back to the English key, so the app never shows
/// an empty label.
class AppTranslations {
  final String languageCode;

  const AppTranslations(this.languageCode);

  bool get isArabic => languageCode == 'ar';
  bool get isFrench => languageCode == 'fr';
  bool get isEnglish => languageCode == 'en';
  bool get isRtl => isArabic;

  /// Translate an English source string.
  String t(String key) {
    if (isEnglish) return key;
    final table = isArabic ? ar : fr;
    return table[key] ?? key;
  }

  /// Translate a string containing `{placeholders}`.
  String tf(String key, Map<String, String> params) {
    var out = t(key);
    params.forEach((k, v) => out = out.replaceAll('{$k}', v));
    return out;
  }

  /// Format a price in the app currency.
  String money(num value) =>
      '${value.toStringAsFixed(0)} ${isArabic ? 'دج' : 'DA'}';

  /// Pick a localized value directly (used by the offline AI engine).
  String pick({required String en, required String ar, required String fr}) {
    if (isArabic) return ar;
    if (isFrench) return fr;
    return en;
  }

  String productDescription(String id, String fallback) {
    if (isEnglish) return fallback;
    final table = isArabic ? _arProductDescriptions : _frProductDescriptions;
    return table[id] ?? fallback;
  }

  /// Localizes loyalty point history entries stored with English prefixes.
  String pointReason(String reason) {
    if (isEnglish) return reason;
    var out = reason;
    if (out.startsWith('Order #')) {
      out = out.replaceFirst('Order #', isArabic ? 'طلب #' : 'Commande #');
    } else if (out.startsWith('Order')) {
      out = out.replaceFirst('Order', isArabic ? 'طلب' : 'Commande');
    }
    if (out.startsWith('Redeemed')) {
      out = out.replaceFirst('Redeemed', isArabic ? 'استبدال' : 'Échange');
    }
    return out;
  }

