  Future<List<Product>> fetchProducts() async {
    try {
      final supabaseProducts = await SupabaseService.getProducts();
      if (supabaseProducts != null && supabaseProducts.isNotEmpty) {
        final valid = supabaseProducts.where((p) => p.image.startsWith('http')).toList();
        if (valid.isNotEmpty) return valid;
      }
    } catch (_) {}

    return _defaultProducts;
  }
